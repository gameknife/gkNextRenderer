        // True when `params` declares a parameter of exactly this name
        // ("c = ch_HAIRC()" has "c"; "screen = ..." does not have "c").
        bool HasNamedParam(const std::string& params, const std::string& name)
        {
            size_t pos = 0;
            while ((pos = params.find(name, pos)) != std::string::npos)
            {
                const bool startOk = pos == 0 || params[pos - 1] == ' ' || params[pos - 1] == ',';
                const size_t end = pos + name.size();
                const bool endOk =
                    end >= params.size() || params[end] == ' ' || params[end] == '=' || params[end] == ',';
                if (startOk && endOk)
                {
                    return true;
                }
                pos = end;
            }
            return false;
        }

        std::string ColorLiteral(const float rgb[3])
        {
            return fmt::format("[{:.2f}, {:.2f}, {:.2f}]", rgb[0], rgb[1], rgb[2]);
        }

        // Part call with the designer's skin (and, for hair, hair color) bound
        // to the module's named parameters; everything else keeps kit defaults
        // so ch_TINT() placeholders stay runtime-tintable.
        std::string PartCall(const FKitModuleInfo& moduleInfo, const float skin[3], const float* hairColor = nullptr)
        {
            std::vector<std::string> args;
            if (hairColor != nullptr && HasNamedParam(moduleInfo.params, "c"))
            {
                args.push_back(fmt::format("c = {}", ColorLiteral(hairColor)));
            }
            if (HasNamedParam(moduleInfo.params, "skin"))
            {
                args.push_back(fmt::format("skin = {}", ColorLiteral(skin)));
            }
            std::string joined;
            for (size_t i = 0; i < args.size(); ++i)
            {
                joined += (i > 0 ? ", " : "") + args[i];
            }
            return fmt::format("{}({})", moduleInfo.name, joined);
        }
