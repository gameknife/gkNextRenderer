    void FCharacterDesigner::SetKit(const FKitInfo* kit)
    {
        heads_.clear();
        hairs_.clear();
        hats_.clear();
        torsos_.clear();
        arms_.clear();
        legs_.clear();
        accs_.clear();
        hasKit_ = false;
        if (kit != nullptr)
        {
            for (const FKitModuleInfo& moduleInfo : kit->modules)
            {
                if (moduleInfo.category == "head")
                    heads_.push_back(moduleInfo);
                else if (moduleInfo.category == "hair")
                    hairs_.push_back(moduleInfo);
                else if (moduleInfo.category == "hat")
                    hats_.push_back(moduleInfo);
                else if (moduleInfo.category == "torso")
                    torsos_.push_back(moduleInfo);
                else if (moduleInfo.category == "arm")
                    arms_.push_back(moduleInfo);
                else if (moduleInfo.category == "leg")
                    legs_.push_back(moduleInfo);
                else if (moduleInfo.category == "acc")
                    accs_.push_back(moduleInfo);
            }
            hasKit_ = !heads_.empty() && !torsos_.empty() && !arms_.empty() && !legs_.empty();
        }
        head = 0;
        hair = hairs_.empty() ? -1 : 0;
        hat = -1;
        torso = 0;
        arm = 0;
        leg = 0;
        accEnabled.assign(accs_.size(), 0);
    }

    std::string FCharacterDesigner::BuildSource(const std::string& kitUsePath) const
    {
        std::string s;
        s += "// generated by ScadLibrary character designer\n";
        s += "$fn = 8;\n";
        s += fmt::format("use <{}>\n\n", kitUsePath);

        s += "module bone_head()\n{\n";
        s += fmt::format("    {};\n", PartCall(heads_[head], skinColor));
        if (hair >= 0 && hair < static_cast<int>(hairs_.size()))
        {
            s += fmt::format("    {};\n", PartCall(hairs_[hair], skinColor, hairColor));
        }
        if (hat >= 0 && hat < static_cast<int>(hats_.size()))
        {
            s += fmt::format("    {};\n", PartCall(hats_[hat], skinColor));
        }
        s += "}\n\n";

        s += fmt::format("module bone_arm_l() {{ {}; }}\n", PartCall(arms_[arm], skinColor));
        s += fmt::format("module bone_arm_r() {{ mirror([1, 0, 0]) {}; }}\n\n", PartCall(arms_[arm], skinColor));
        s += fmt::format("module bone_leg_l() {{ {}; }}\n", PartCall(legs_[leg], skinColor));
        s += fmt::format("module bone_leg_r() {{ mirror([1, 0, 0]) {}; }}\n\n", PartCall(legs_[leg], skinColor));

        s += "module bone_torso()\n{\n";
        s += fmt::format("    {};\n", PartCall(torsos_[torso], skinColor));
        for (size_t i = 0; i < accs_.size(); ++i)
        {
            if (i < accEnabled.size() && accEnabled[i] != 0)
            {
                s += fmt::format("    {}();\n", accs_[i].name);
            }
        }
        s += "    translate(ch_pivot_head())  bone_head();\n";
        s += "    translate(ch_pivot_arm_l()) bone_arm_l();\n";
        s += "    translate(ch_pivot_arm_r()) bone_arm_r();\n";
        s += "}\n\n";

        s += "module bone_root()\n{\n";
        s += "    translate(ch_pivot_torso()) bone_torso();\n";
        s += "    translate(ch_pivot_leg_l()) bone_leg_l();\n";
        s += "    translate(ch_pivot_leg_r()) bone_leg_r();\n";
        s += "}\n\n";
        s += "bone_root();\n\n";

        s += "anim_idle = ch_clip_idle();\n";
        s += "anim_walk = ch_clip_walk();\n";
        s += "anim_sit  = ch_clip_sit();\n";
        s += "anim_work = ch_clip_work();\n";
        s += "anim_wave = ch_clip_wave();\n";
        return s;
    }

